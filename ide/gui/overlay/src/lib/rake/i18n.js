export const makeTranslator = locale => {
    const table = (locale || '').toLowerCase().startsWith('ja') ? messages.ja : messages.en;
    return (key, values = {}) => (table[key] || messages.en[key] || key)
        .replace(/\{(\w+)\}/g, (match, name) => (name in values ? String(values[name]) : match));
};
